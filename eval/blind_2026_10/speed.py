#!/usr/bin/env python3
"""Speed comparison for the blind benchmark (PREREGISTRATION.md section 8 timing clause).

    speed.py [PRIVATE_DIR]      # default /Users/niks/hive-blind-eval-private -> report/SPEED.md

Every number comes from files written during the benchmark: annotations/tanvi/timelog.csv,
annotations/tanvi/targets.csv (which panels were labeled), annotations/crop_map.csv,
runs/<PMCID>/timing.json and llm_candidates.json (crops sent to the model), report/results.json
(coverage). Nothing is typed in by hand except the clearly labeled review-time assumption.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

from score_blind import HERE, crop_panels, minutes, read_csv

REVIEW_FRACTIONS = (0.25, 0.5)   # ASSUMPTION, not measured: checking time as a share of manual time


def main(private: Path) -> str:
    ann = HERE / "annotations" / "tanvi"
    papers = json.loads((HERE / "papers.json").read_text())["papers"]
    rank = {p["draw_rank"]: p["pmcid"] for p in papers}
    inv, targets, cmap = read_csv(ann / "panels.csv"), read_csv(ann / "targets.csv"), read_csv(HERE / "annotations" / "crop_map.csv")
    labeled = {(r["paper_pmcid"], r["panel_id"]) for r in targets}            # locked labels: 8 panels
    res = json.loads((HERE / "report" / "results.json").read_text())

    groups = []
    for row in read_csv(ann / "timelog.csv"):
        pmcids = [rank[int(n)] for n in re.findall(r"\d+", row["task"])]   # "paper 3+4" -> draw ranks 3, 4
        g = {"name": row["task"], "pmcids": pmcids, "manual_min": minutes(row["minutes"]),
             "panels": 0, "no_crop": 0, "auto_s": 0.0, "sent": 0, "matched_crops": 0, "matched_s": 0.0}
        for pmcid in pmcids:
            t = json.loads((private / "runs" / pmcid / "timing.json").read_text())
            secs = t["preprocess_seconds"] + t["extract_seconds"]
            per_crop = secs / t["panels_queried"]   # no per-crop timestamps exist; paper average
            sent = {Path(c["candidate_path"]).name for c in json.loads((private / "runs" / pmcid / "llm_candidates.json").read_text())}
            mp = crop_panels([r for r in cmap if r["paper_pmcid"] == pmcid], [r for r in inv if r["paper_pmcid"] == pmcid])
            hit = [c for c in sent if isinstance(mp.get(c), list) and any((pmcid, i) in labeled for i in mp[c])]
            g["panels"] += sum(1 for p, _ in labeled if p == pmcid)
            g["auto_s"] += secs
            g["sent"] += t["panels_queried"]
            g["matched_crops"] += len(hit)
            seen = {i for c in hit for i in mp[c]}
            g["no_crop"] += sum(1 for p, i in labeled if p == pmcid and i not in seen)
            g["matched_s"] += len(hit) * per_crop
        groups.append(g)

    tot = {k: sum(g[k] for g in groups) for k in ("manual_min", "panels", "no_crop", "auto_s", "sent", "matched_crops", "matched_s")}
    tot["name"] = "all"
    assert tot["panels"] == res["timing"]["panels_labeled"], "labeled-panel count disagrees with results.json"

    def row(g):
        m_pp = g["manual_min"] / g["panels"]
        h_pp = g["matched_s"] / g["panels"]
        return (f"| {g['name']} | {g['manual_min']:.1f} min / {g['panels']} = **{m_pp:.1f} min** | "
                f"{g['matched_crops']} crops x paper avg = {g['matched_s']:.0f} s / {g['panels']} = **{h_pp:.0f} s** | "
                f"**{m_pp * 60 / h_pp:.0f}x** | **{100 * (1 - h_pp / (m_pp * 60)):.1f}%** | "
                f"{g['auto_s'] / 60:.1f} min ({g['sent']} crops) -> {g['manual_min'] * 60 / g['auto_s']:.1f}x, "
                f"{100 * (1 - g['auto_s'] / (g['manual_min'] * 60)):.0f}% |")

    ratios = [g["manual_min"] / g["panels"] * 60 / (g["matched_s"] / g["panels"]) for g in groups]
    whole = [g["manual_min"] * 60 / g["auto_s"] for g in groups]
    corr, ann_n = _counts(res)
    cov_frac = corr / ann_n
    m_pp = tot["manual_min"] / tot["panels"]
    h_pp_min = tot["matched_s"] / tot["panels"] / 60
    review = [(f, h_pp_min + (1 - cov_frac) * m_pp + f * m_pp) for f in REVIEW_FRACTIONS]

    out = [
        "# Speed comparison, blind benchmark October 2026 (generated by speed.py; do not edit by hand)",
        "",
        "Measured during the benchmark: Tanvi's time log (manual) and `timing.json` wall-clock per paper (HiveBlot:",
        "Stage 1 preprocessing + model stage, `claude-opus-5`, `WBM_CONCURRENCY=1`). Both produce the same schema:",
        "target, modification, cell line, treatment, lane-level band calls.",
        "",
        "**Matched or averaged?** Averaged. The run wrote no per-crop timestamps (`evidence_records.jsonl` has one",
        "line per record and no time field; the extraction log has no times). HiveBlot time on the labeled panels is",
        "estimated as (crops sent to the model that map to a labeled panel, via `crop_map.csv`) x (that paper's",
        "wall-clock / crops sent). The last column is the conservative check: HiveBlot's whole-paper run, every",
        "crop it detected, against the human's time for only the panels she labeled.",
        "",
        "| Paper group (time log row) | Manual per labeled panel | HiveBlot per labeled panel (estimate) | Speed-up | Time reduction | Whole-paper check |",
        "|---|---|---|---|---|---|",
        *[row(g) for g in groups],
        row(tot),
        "",
        f"- Range across paper groups: **{min(ratios):.0f}x to {max(ratios):.0f}x** per labeled panel; "
        f"whole-paper check **{min(whole):.1f}x to {max(whole):.1f}x**.",
        f"- {tot['no_crop']} of {tot['panels']} labeled panels had no crop sent to the model (HiveBlot missed it), so "
        "it adds 0 s to the per-panel estimate while producing nothing for that panel. This flatters the per-panel ratio.",
        f"- The safest single figure is the pooled whole-paper check, **{tot['manual_min'] * 60 / tot['auto_s']:.0f}x** "
        f"({tot['auto_s'] / 60:.1f} min vs {tot['manual_min']:.0f} min for the same 3 papers).",
        "",
        "## Time saved including review (ASSUMPTION, not measured)",
        "",
        "The figures above exclude review. In the same test HiveBlot's stated values were 92% correct but covered",
        f"{corr}/{ann_n} ({100 * cov_frac:.0f}%) of the labeled values, so a researcher still checks its output and",
        "fills the gaps. Nobody timed that. Model: per panel = HiveBlot time + (uncovered share x manual time) +",
        "(review fraction x manual time), with the review fraction assumed, not measured:",
        "",
        "| Assumed review fraction | Minutes per panel | vs manual | Time reduction |",
        "|---|---|---|---|",
        *[f"| {f:.0%} | {t:.1f} | {m_pp:.1f} | {100 * (1 - t / m_pp):.0f}% |" for f, t in review],
        "",
        "## Caveats",
        "",
        "- One annotator, one time log, two rows; papers 3 and 4 were logged together. 8 labeled panels (the locked",
        "  labels; tier ii counts 9 after one row moved panel, which would make the manual per-panel figure smaller).",
        "- The log does not separate reading the paper, inventorying panels and labeling; all of it is manual time.",
        "- Wall-clock on one laptop through the `claude_cli` transport, one crop at a time. Model latency dominates and",
        "  changes with load; production uses the API backend.",
        "- The human chose which panels to label; HiveBlot processed every detected crop, including non-Western ones.",
        "- 3 papers. Not a literature-wide figure. Do not quote a time-saved percentage without the review caveat.",
        "",
    ]
    return "\n".join(out)


def _counts(res) -> tuple[int, int]:
    """CORRECT and annotated values, tier (ii) ALL FIELDS, from results.json."""
    m = res["tiers"]["adjudicated"]["metrics"]["ALL FIELDS"]["accuracy"]
    a, b = re.match(r"(\d+)/(\d+)", m).groups()
    return int(a), int(b)


if __name__ == "__main__":
    md = main(Path(sys.argv[1] if len(sys.argv) > 1 else "/Users/niks/hive-blind-eval-private"))
    (HERE / "report" / "SPEED.md").write_text(md)
    print(md)
