-- =====================================================================
-- HiveBlot -- Migration 008: saved results backend grants
-- =====================================================================
-- On the hosted project the table was created by Supabase migration
-- 20261001071053; IF NOT EXISTS gives a fresh database the same shape.
-- Browser code never accesses it directly; FastAPI uses the existing
-- hive_feedback writer role, with the same session_id value already used by
-- search_history.
BEGIN;

CREATE TABLE IF NOT EXISTS public.saved_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id TEXT NULL,
    user_id UUID NULL,
    record_id BIGINT NULL
        REFERENCES public.western_blot_records(id)
        ON DELETE SET NULL,
    stable_row_key TEXT NOT NULL,
    saved_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT saved_results_owner_required
        CHECK (session_id IS NOT NULL OR user_id IS NOT NULL),
    CONSTRAINT saved_results_session_id_length
        CHECK (
            session_id IS NULL
            OR (length(session_id) >= 1 AND length(session_id) <= 128)
        )
);

-- Plain Postgres (CI, local) has no Supabase auth schema.
DO $$
BEGIN
    IF to_regclass('auth.users') IS NOT NULL AND NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'saved_results_user_id_fkey'
    ) THEN
        ALTER TABLE public.saved_results
            ADD CONSTRAINT saved_results_user_id_fkey
            FOREIGN KEY (user_id) REFERENCES auth.users(id) ON DELETE CASCADE;
    END IF;
END $$;

CREATE UNIQUE INDEX IF NOT EXISTS saved_results_unique_session_record
ON public.saved_results (session_id, stable_row_key)
WHERE session_id IS NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS saved_results_unique_user_record
ON public.saved_results (user_id, stable_row_key)
WHERE user_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS saved_results_record_id_idx
ON public.saved_results (record_id);

CREATE INDEX IF NOT EXISTS saved_results_session_recent_idx
ON public.saved_results (session_id, saved_at DESC)
WHERE session_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS saved_results_user_recent_idx
ON public.saved_results (user_id, saved_at DESC)
WHERE user_id IS NOT NULL;

REVOKE ALL ON TABLE public.saved_results FROM anon, authenticated;
REVOKE ALL ON SEQUENCE public.saved_results_id_seq FROM anon, authenticated;

GRANT SELECT, INSERT, DELETE
ON TABLE public.saved_results
TO hive_feedback;

GRANT USAGE, SELECT
ON SEQUENCE public.saved_results_id_seq
TO hive_feedback;

ALTER TABLE public.saved_results ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS hive_feedback_select_saved_results ON public.saved_results;
CREATE POLICY hive_feedback_select_saved_results
ON public.saved_results
FOR SELECT
TO hive_feedback
USING (true);

DROP POLICY IF EXISTS hive_feedback_insert_saved_results ON public.saved_results;
CREATE POLICY hive_feedback_insert_saved_results
ON public.saved_results
FOR INSERT
TO hive_feedback
WITH CHECK (true);

DROP POLICY IF EXISTS hive_feedback_delete_saved_results ON public.saved_results;
CREATE POLICY hive_feedback_delete_saved_results
ON public.saved_results
FOR DELETE
TO hive_feedback
USING (true);

COMMIT;
